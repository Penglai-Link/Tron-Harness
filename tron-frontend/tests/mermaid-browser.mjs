/** Real Tron/Framework SSE with a fixture that holds before and after closing fences. */
export async function verifyTronMermaid(page, { modelBase }) {
  const checks = [];
  const check = (name, value) => { if (!value) throw new Error(name); checks.push(name); };
  await page.getByRole("button", { name: "New Chat", exact: true }).click();
  await page.getByRole("button", { name: "Select chat model", exact: true }).click();
  await page.getByRole("menuitemradio", { name: "Composer Preview", exact: true }).click();
  const received = page.waitForResponse(response => new URL(response.url()).pathname.endsWith("messages/stream"));
  await page.locator('[data-theme-part="chat-input"]').fill("MERMAID_ACCEPTANCE 请给出 Tron 架构图和消息时序图。");
  await page.locator('[data-theme-part="chat-input"]').press("Enter");
  const response = await received;
  check("SSE accepted", response.status() === 200);
  await page.locator('.ef-chat__mermaid[data-mermaid-state="incomplete"]').waitFor({ timeout: 20000 });
  check("partial streamed diagram stays source", await page.locator(".ef-chat__mermaid > svg").count() === 0);
  check("partial diagram arrives before model completion", await page.getByRole("button", { name: "Stop", exact: true }).isVisible());
  await page.request.get(`${modelBase}/mermaid/release`);
  await page.waitForFunction(() => document.querySelectorAll('.ef-chat__mermaid[data-mermaid-state="ready"]').length === 2, {}, { timeout: 30000 });
  check("both diagrams render before completion", await page.getByRole("button", { name: "Stop", exact: true }).isVisible());
  const graph = page.getByRole("button", { name: "View Mermaid diagram", exact: true }).first();
  await graph.click();
  const dialog = page.locator("dialog.ef-chat__mermaid-dialog");
  await dialog.waitFor();
  check("localized image dialog opens", await dialog.getAttribute("aria-label") === "Mermaid diagram preview");
  const image = dialog.getByRole("img", { name: "Mermaid", exact: true });
  await image.evaluate(node => node.decode());
  check("SVG image loads in the large preview", await image.evaluate(node => node.naturalWidth > 0));
  const width = await image.evaluate(node => node.getBoundingClientRect().width);
  await dialog.getByRole("button", { name: "Zoom in", exact: true }).click();
  check("preview can zoom", await image.evaluate(node => node.getBoundingClientRect().width) > width);
  await dialog.getByRole("button", { name: "Fit to window", exact: true }).click();
  await page.screenshot({ path: "output/playwright/tron-mermaid-preview.png", animations: "disabled" });
  await page.keyboard.press("Escape"); await dialog.waitFor({ state: "detached" });
  await graph.press("Enter"); await dialog.waitFor();
  await page.mouse.click(2, 2); await dialog.waitFor({ state: "detached" });
  check("Escape, keyboard reopening, and backdrop dismissal work", await page.locator("dialog").count() === 0);
  await page.request.get(`${modelBase}/mermaid/release`);
  const body = await response.text();
  check("run completes without error", !body.includes("event: RUN_ERROR") && body.includes("RUN_FINISHED"));
  await page.getByRole("button", { name: "Stop", exact: true }).waitFor({ state: "hidden" });
  const session = new URL(page.url()).searchParams.get("sessionCode");
  await page.reload();
  await page.waitForFunction(() => document.querySelectorAll('.ef-chat__mermaid[data-mermaid-state="ready"]').length === 2, {}, { timeout: 30000 });
  check("history restores both diagrams", await page.locator(".ef-chat__mermaid > svg").count() === 2);
  await page.getByRole("button", { name: "View Mermaid diagram", exact: true }).first().click();
  await dialog.waitFor();
  await dialog.getByRole("button", { name: "Close image preview", exact: true }).click();
  await dialog.waitFor({ state: "detached" });
  check("history diagram preview opens and closes", await page.locator("dialog").count() === 0);
  return { session, passed: checks.length, checks };
}
