// @vitest-environment jsdom
import { StrictMode } from "react";
import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { afterEach, expect, it, vi } from "vitest";
import { SkillAgentGrants } from "./SkillAgentGrants";
import type { RegistrySkillRecord } from "../model";
const fixture = vi.hoisted(() => ({ fetch: vi.fn(), save: vi.fn() }));
vi.mock("@/domain/skill/api", () => ({ fetchSkillAgents: fixture.fetch, setSkillAgents: fixture.save }));
vi.mock("@/domain/dude/api/dudeApi", () => ({ listDudes: async () => [] }));
vi.mock("@/domain/agent/api/agentManagementApi", () => ({ fetchWorkspaceInternalAgents: async () => [{agentCode:"main-agent", name:"Main Agent"}] }));
vi.mock("@/components/ui/toast", () => ({ useToast: () => ({error:vi.fn()}) }));
vi.mock("react-i18next", () => ({useTranslation: () => ({t:(key:string) => key})}));
afterEach(cleanup);
it("keeps a user's Agent selection when an earlier StrictMode load finishes late", async () => {
  let old!: (value: {agentCodes:string[]}) => void;
  let latest!: (value: {agentCodes:string[]}) => void;
  fixture.fetch.mockReturnValueOnce(new Promise(resolve => {old=resolve;})).mockReturnValueOnce(new Promise(resolve => {latest=resolve;}));
  fixture.save.mockResolvedValue({agentCodes:["main-agent"]});
  const saved = vi.fn();
  render(<StrictMode><QueryClientProvider client={new QueryClient()}><SkillAgentGrants skill={{skillName:"business"} as RegistrySkillRecord} onClose={() => {}} onSaved={saved} /></QueryClientProvider></StrictMode>);
  await waitFor(() => expect(fixture.fetch).toHaveBeenCalledTimes(2));
  await act(async () => latest({agentCodes:[]}));
  const checkbox = await screen.findByRole<HTMLInputElement>("checkbox", {name:/Main Agent/});
  fireEvent.click(checkbox);
  expect(checkbox.checked).toBe(true);
  await act(async () => old({agentCodes:[]}));
  expect(checkbox.checked).toBe(true);
  fireEvent.click(screen.getByRole("button", {name:"agentSkills.save"}));
  await waitFor(() => expect(fixture.save).toHaveBeenCalledWith("business", ["main-agent"]));
  await waitFor(() => expect(saved).toHaveBeenCalled());
});
