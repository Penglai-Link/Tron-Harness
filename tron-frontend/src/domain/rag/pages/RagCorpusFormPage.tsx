function hasGraphStorageTarget(storageTargets: RagStorageTargetFormState[]) {
  return storageTargets.some((target) => target.backend === "GRAPH");
}

function normalizeGraphCapability(form: RagCorpusFormState) {
  if (hasGraphStorageTarget(form.storageTargets)) return form;
  return {
    ...form,
    graphEnabled: false,
  };
}

function storageTargetValue(target: RagStorageTargetFormState | undefined, index: number) {
  if (!target) return undefined;
  return ragStorageTargetOptionLabel(target, index);
}

function hasCustomStorageConfiguration(form: RagCorpusFormState) {
  const defaultTargetIds = new Set(
    Object.values(ragStorageTargetFormDefaults.defaultSegmentBindings).filter(Boolean),
  );
  const defaultSummaryTreeTargetId = ragStorageTargetFormDefaults.defaultSummaryTreeTargetId;
  const hasCustomTarget = form.storageTargets.some((target) => {
    const targetId = target.id.trim();
    const isDefaultSummaryTreeTarget = (
      form.treeEnabled
      && targetId === defaultSummaryTreeTargetId
      && target.backend === "SQLITE"
      && target.tableAutoGenerated
    );
    if (target.backend === "GRAPH") return true;
    if (!defaultTargetIds.has(targetId) && !isDefaultSummaryTreeTarget) return true;
    return target.backend === "SQLITE" && !target.tableAutoGenerated;
  });
  const hasCustomBinding = editableStorageSegmentOrder.some((segmentKey) => (
    segmentKey === "tree"
      ? form.treeEnabled && form.segmentBindings.tree.trim() !== defaultSummaryTreeTargetId
      : form.segmentBindings[segmentKey].trim() !== ragStorageTargetFormDefaults.defaultSegmentBindings[segmentKey]
  ));
  return hasCustomTarget || hasCustomBinding;
}

