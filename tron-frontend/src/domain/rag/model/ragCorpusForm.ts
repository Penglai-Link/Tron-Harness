function ensureUniqueTargetId(preferredId: string, usedIds: Set<string>) {
  let nextId = preferredId;
  let suffix = 2;
  while (usedIds.has(nextId)) {
    nextId = `${preferredId}-${suffix}`;
    suffix += 1;
  }
  usedIds.add(nextId);
  return nextId;
}

function sanitizeKebabToken(value: string) {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function sanitizeSnakeToken(value: string) {
  return sanitizeKebabToken(value).replace(/-/g, "_");
}

function toPascalCase(value: string) {
  return sanitizeKebabToken(value)
    .split("-")
    .filter(Boolean)
    .map((token) => `${token.slice(0, 1).toUpperCase()}${token.slice(1)}`)
    .join("");
}

function getCorpusIdentifierSeed(code: string, name: string) {
  return sanitizeKebabToken(code) || sanitizeKebabToken(name) || "temporary-corpus";
}

function getEditableStorageIdentifierSeed(code: string, name: string) {
  return sanitizeSnakeToken(code) || sanitizeSnakeToken(name) || "corpus";
}

function deriveSqliteTargetTable(
  target: Pick<RagStorageTargetFormState, "formId" | "id">,
  corpusCode: string,
  corpusName: string,
  visibleIndex?: number,
) {
  const corpusIdentifier = getEditableStorageIdentifierSeed(corpusCode, corpusName);
  if (target.id === targetIdBySegment.source) return `rag_${corpusIdentifier}_sources`;
  if (target.id === targetIdBySegment.textUnit) return `rag_${corpusIdentifier}_text_units`;
  if (target.id === targetIdBySegment.vector) return `rag_${corpusIdentifier}_vectors`;
  if (target.id === targetIdBySegment.tree) return `rag_${corpusIdentifier}_tree_nodes`;

  const targetNumber = visibleIndex === undefined
    ? (Number(target.formId.replace("target-form-", "")) || 1)
    : visibleIndex + 1;
  return `rag_${corpusIdentifier}_target_${targetNumber}`;
}

function deriveGraphTargetNamespace(
  target: Pick<RagStorageTargetFormState, "id">,
  corpusCode: string,
  corpusName: string,
) {
  const corpusIdentifier = getEditableStorageIdentifierSeed(corpusCode, corpusName);
  if (target.id === targetIdBySegment.tree) return `rag_${corpusIdentifier}_tree`;
  return defaultGraphNamespaces.fulltext;
}

function deriveGraphTargetNodeLabel(target: Pick<RagStorageTargetFormState, "id">) {
  return target.id === targetIdBySegment.tree ? defaultGraphNodeLabels.tree : defaultGraphNodeLabels.fulltext;
}

function createStorageTarget(
  segmentKey: RagEditableStorageSegmentKey | undefined,
  formId: string,
  corpusCode: string,
  corpusName: string,
): RagStorageTargetFormState {
  const targetId = segmentKey ? targetIdBySegment[segmentKey] : `target-${formId.replace("target-form-", "") || "1"}`;
  const sourceLike = segmentKey === "source";
  return {
    backend: "SQLITE",
    codeStrategy: "",
    formId,
    id: targetId,
    namespace: deriveGraphTargetNamespace({ id: targetId }, corpusCode, corpusName),
    nodeLabel: sourceLike ? defaultGraphNodeLabels.source : deriveGraphTargetNodeLabel({ id: targetId }),
    table: deriveSqliteTargetTable({ formId, id: targetId }, corpusCode, corpusName),
    tableAutoGenerated: true,
  };
}

function createDefaultStorageTargets(corpusCode: string, corpusName: string) {
  return defaultStorageTargetSegmentOrder.map((segmentKey, index) => (
    createStorageTarget(segmentKey, `target-form-${index + 1}`, corpusCode, corpusName)
  ));
}

function buildImplicitDiagnosticsTarget(
  storageTargets: RagStorageTargetFormState[],
  segmentBindings: Record<RagEditableStorageSegmentKey, string>,
  corpusCode: string,
  corpusName: string,
): RagStorageTargetBinding | undefined {
  const sourceTargetId = segmentBindings.source.trim();
  if (!sourceTargetId) return undefined;

  const sourceTarget = storageTargets.find((target) => target.id.trim() === sourceTargetId);
  if (!sourceTarget) return undefined;

  const corpusIdentifier = getCorpusIdentifierSeed(corpusCode, corpusName);
  const preferredTargetId = `${corpusIdentifier}-diagnostics`;
  const usedIds = new Set(storageTargets.map((target) => target.id.trim()).filter(Boolean));
  const diagnosticsTargetId = ensureUniqueTargetId(preferredTargetId, usedIds);

  if (sourceTarget.backend === "GRAPH") {
    return {
      backend: "GRAPH",
      codeStrategy: sourceTarget.codeStrategy.trim() || undefined,
      id: diagnosticsTargetId,
      layout: "GRAPH_SINGLE_NODE",
      namespace: sourceTarget.namespace.trim() || undefined,
      nodeLabel: `${toPascalCase(corpusIdentifier)}Diagnostics`,
    };
  }

  return {
    backend: "SQLITE",
    id: diagnosticsTargetId,
    layout: "TABLE",
    table: `rag_${sanitizeSnakeToken(corpusIdentifier)}_diagnostics`,
  };
}

function buildStorageTargetBinding(target: RagStorageTargetFormState, graphLayout: "GRAPH_SINGLE_NODE" | "GRAPH_TREE" = "GRAPH_SINGLE_NODE"): RagStorageTargetBinding {
  if (target.backend === "GRAPH") {
    return {
      backend: "GRAPH",
      codeStrategy: target.codeStrategy.trim() || undefined,
      id: target.id.trim(),
      layout: graphLayout,
      namespace: target.namespace.trim() || undefined,
      nodeLabel: target.nodeLabel.trim() || undefined,
    };
  }

  return {
    backend: "SQLITE",
    id: target.id.trim(),
    layout: "TABLE",
    table: target.table.trim() || undefined,
  };
}

function buildStorageBindingFromTargets(
  storageTargets: RagStorageTargetFormState[],
  segmentBindings: Record<RagEditableStorageSegmentKey, string>,
  corpusCode: string,
  corpusName: string,
): RagStorageBinding {
  const diagnosticsTarget = buildImplicitDiagnosticsTarget(storageTargets, segmentBindings, corpusCode, corpusName);
  const treeTargetId = segmentBindings.tree.trim();
  const bindings: Partial<Record<RagStorageSegmentKey, string>> = Object.fromEntries(
    editableStorageSegmentOrder
      .map((segmentKey) => [segmentKey, segmentBindings[segmentKey].trim()])
      .filter((entry): entry is [RagEditableStorageSegmentKey, string] => Boolean(entry[1])),
  );
  if (diagnosticsTarget) {
    bindings.diagnostics = diagnosticsTarget.id;
  }
  return {
    bindings,
    mode: "TARGETED",
    targets: [
      ...storageTargets.map((target) => buildStorageTargetBinding(
        target,
        target.id.trim() && target.id.trim() === treeTargetId ? "GRAPH_TREE" : "GRAPH_SINGLE_NODE",
      )),
      ...(diagnosticsTarget ? [diagnosticsTarget] : []),
    ],
  };
}

function bindingSummaryFromTargets(
  storageTargets: RagStorageTargetFormState[],
  segmentBindings: Record<RagEditableStorageSegmentKey, string>,
  corpusCode: string,
  corpusName: string,
) {
  return formatRagStorageBinding(buildStorageBindingFromTargets(storageTargets, segmentBindings, corpusCode, corpusName));
}

function nextStorageTargetFormId(storageTargets: RagStorageTargetFormState[]) {
  const maxIndex = storageTargets.reduce((currentMax, target) => {
    const match = target.formId.match(/target-form-(\d+)$/);
    if (!match) return currentMax;
    return Math.max(currentMax, Number(match[1]));
  }, 0);
  return `target-form-${maxIndex + 1}`;
}

function createStorageTargetOptionLabel(target: RagStorageTargetFormState, visibleIndex?: number) {
  const physicalTarget = buildStorageTargetBinding(target);
  void visibleIndex;
  return physicalTarget.backend === "GRAPH"
    ? `${physicalTarget.namespace ?? ragCorpusFormT("labels.unbound", "Unbound")}/${physicalTarget.nodeLabel ?? ragCorpusFormT("labels.node", "Node")}`
    : `${physicalTarget.table ?? ragCorpusFormT("labels.unbound", "Unbound")}`;
}

