function contractFieldDefinitions(
  baseDefinitions: RagContractFieldDefinition[],
  optionalDefinitions: RagContractFieldDefinition[],
  mapping?: Record<string, string>,
) {
  if (!mapping) return [...baseDefinitions];
  return [
    ...baseDefinitions,
    ...optionalDefinitions.filter((definition) => Object.hasOwn(mapping, definition.logicalName)),
  ];
}

function sourceContractFieldDefinitions(mapping?: Record<string, string>) {
  return contractFieldDefinitions(
    baseSourceContractFieldDefinitions,
    sourceOptionalContractFieldDefinitions,
    mapping,
  );
}

function textUnitContractFieldDefinitions(mapping?: Record<string, string>) {
  return contractFieldDefinitions(baseTextUnitContractFieldDefinitions, [], mapping);
}

