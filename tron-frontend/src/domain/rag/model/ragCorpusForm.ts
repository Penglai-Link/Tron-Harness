function nextFormRowId(rows: Array<{ id: string }>, prefix: string) {
  const maxIndex = rows.reduce((currentMax, row) => {
    const match = row.id.match(new RegExp(`^${prefix}-(\\d+)$`));
    if (!match) return currentMax;
    return Math.max(currentMax, Number(match[1]));
  }, 0);
  return `${prefix}-${maxIndex + 1}`;
}

function createContractMappingRows(definitions: RagContractFieldDefinition[], prefix: string) {
  return definitions.map((definition, index) => ({
    column: definition.column,
    id: `${prefix}-${index + 1}`,
    isContract: true,
    logicalName: definition.logicalName,
  }));
}

function rowsFromFilterSchema(schema: RagCorpusFilterSchema): RagFilterFieldFormRow[] {
  const rows = Object.entries(schema.fields).map(([name, field], index) => ({
    id: `filter-${index + 1}`,
    name,
    operatorsInput: (field.operators?.length ? field.operators : ["eq", "in"]).join(", "),
    type: field.type,
  }));
  return rows.length ? rows : [{ ...defaultFilterField }];
}

function rowsFromMapping(
  mapping: Record<string, string>,
  prefix: string,
  contractDefinitions: RagContractFieldDefinition[],
) {
  const rows = createContractMappingRows(contractDefinitions, prefix).map((row) => ({
    ...row,
    column: mapping[row.logicalName] ?? row.column,
  }));
  const seenLogicalNames = new Set(rows.map((row) => row.logicalName));
  let nextIndex = rows.length + 1;
  Object.entries(mapping).forEach(([logicalName, column]) => {
    if (seenLogicalNames.has(logicalName)) return;
    rows.push({
      column,
      id: `${prefix}-${nextIndex}`,
      isContract: false,
      logicalName,
    });
    nextIndex += 1;
  });
  return rows;
}

function collectFieldMappingOptionsFromRows(
  rows: RagFieldMappingFormRow[],
  segment: RagFieldMappingSegment,
  existing = new Map<string, { column: string; columns: Set<string>; segments: Set<RagFieldMappingSegment> }>(),
) {
  rows.forEach((row) => {
    const logicalName = row.logicalName.trim();
    const column = row.column.trim();
    if (!logicalName || !column) return;
    const current = existing.get(logicalName) ?? {
      column,
      columns: new Set<string>(),
      segments: new Set<RagFieldMappingSegment>(),
    };
    current.columns.add(column);
    current.segments.add(segment);
    existing.set(logicalName, current);
  });
  return existing;
}

function collectFieldMappingOptions(form: Pick<RagCorpusFormState, "sourceMappings" | "textUnitMappings">) {
  const options = collectFieldMappingOptionsFromRows(form.sourceMappings, "source");
  return collectFieldMappingOptionsFromRows(form.textUnitMappings, "textUnit", options);
}

function resolveFilterFieldColumn(
  form: Pick<RagCorpusFormState, "sourceMappings" | "textUnitMappings">,
  logicalName: string,
) {
  const option = collectFieldMappingOptions(form).get(logicalName.trim());
  if (!option || option.columns.size !== 1) return undefined;
  return option.column;
}

function storageTargetFromBinding(target: RagStorageTargetBinding, index: number): RagStorageTargetFormState {
  if (target.backend === "GRAPH") {
    return {
      backend: "GRAPH",
      codeStrategy: target.codeStrategy ?? "CORPUS_SOURCE_VERSION_SCOPE_HASH",
      formId: `target-form-${index + 1}`,
      id: target.id,
      namespace: target.namespace ?? "",
      nodeLabel: target.nodeLabel ?? "",
      table: "",
      tableAutoGenerated: false,
    };
  }

  return {
    backend: "SQLITE",
    codeStrategy: "",
    formId: `target-form-${index + 1}`,
    id: target.id,
    namespace: "",
    nodeLabel: "",
    table: target.table ?? "",
    tableAutoGenerated: false,
  };
}

function resolveStorageTarget(
  storageTargets: RagStorageTargetFormState[],
  segmentBindings: Record<RagEditableStorageSegmentKey, string>,
  segmentKey: RagEditableStorageSegmentKey,
) {
  const targetId = segmentBindings[segmentKey].trim();
  if (!targetId) return undefined;
  return storageTargets.find((target) => target.id.trim() === targetId);
}

function shouldRemoveAutoSummaryTreeTarget(
  target: RagStorageTargetFormState,
  treeTargetId: string,
  segmentBindings: Record<RagEditableStorageSegmentKey, string>,
) {
  if (target.id.trim() !== treeTargetId) return false;
  if (target.id.trim() !== targetIdBySegment.tree) return false;
  if (target.backend !== "SQLITE" || !target.tableAutoGenerated) return false;
  return !editableStorageSegmentOrder.some((segmentKey) => (
    segmentKey !== "tree" && segmentBindings[segmentKey].trim() === treeTargetId
  ));
}

export function setRagCorpusSummaryTreeEnabled(
  form: RagCorpusFormState,
  enabled: boolean,
): RagCorpusFormState {
  if (enabled) {
    const existingTreeTarget = form.storageTargets.find((target) => target.id.trim() === targetIdBySegment.tree);
    const storageTargets = existingTreeTarget
      ? form.storageTargets
      : [
        ...form.storageTargets,
        createStorageTarget(
          "tree",
          nextStorageTargetFormId(form.storageTargets),
          form.code,
          form.name,
        ),
      ];
    const segmentBindings = {
      ...form.segmentBindings,
      tree: targetIdBySegment.tree,
    };
    return {
      ...form,
      segmentBindings,
      storageBinding: bindingSummaryFromTargets(storageTargets, segmentBindings, form.code, form.name),
      storageTargets,
      treeEnabled: true,
    };
  }

  const treeTargetId = form.segmentBindings.tree.trim();
  const segmentBindings = {
    ...form.segmentBindings,
    tree: "",
  };
  const storageTargets = treeTargetId
    ? form.storageTargets.filter((target) => !shouldRemoveAutoSummaryTreeTarget(target, treeTargetId, segmentBindings))
    : form.storageTargets;
  return {
    ...form,
    segmentBindings,
    storageBinding: bindingSummaryFromTargets(storageTargets, segmentBindings, form.code, form.name),
    storageTargets,
    treeEnabled: false,
  };
}

