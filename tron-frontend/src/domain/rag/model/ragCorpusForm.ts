function deriveRoutesInputFromCapabilities(
  capabilities: Pick<RagCorpusCapabilities, "fulltext" | "graph" | "tree" | "vector">,
) {
  return [
    capabilities.fulltext ? "FULLTEXT" : "",
    capabilities.vector ? "VECTOR" : "",
    capabilities.tree && capabilities.fulltext ? "TREE_FULLTEXT" : "",
    capabilities.tree && capabilities.vector ? "TREE_VECTOR" : "",
    capabilities.graph ? "GRAPH" : "",
  ]
    .filter(Boolean)
    .join(", ");
}

